-- =====================================================================
-- V1: Esquema inicial - Cobranza Inteligente (Distribuidora de Lacteos)
-- PostgreSQL. Un deploy por cliente (sin empresa_id).
--
-- Convenciones (las mismas del proyecto de retail):
--   * Ids: BIGINT IDENTITY (GenerationType.IDENTITY).
--   * Enteros: INT -> Integer (SMALLINT obligaria a usar Short en Java).
--   * Montos: NUMERIC(12,2).
--   * Enums: VARCHAR + CHECK, para mapear con @Enumerated(EnumType.STRING).
--   * Instantes (cuando paso algo): TIMESTAMPTZ -> java.time.Instant.
--     Render corre en UTC y el negocio en America/Mexico_City; con zona
--     no hay pagos de las 7 pm que "caen" al dia siguiente.
--   * Fechas de negocio (emision, vencimiento): DATE -> LocalDate.
--   * Lo que viene del sistema de ventas trae su llave de origen UNIQUE
--     (codigo_origen / folio_origen) para que importar sea idempotente.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. configuracion (una sola fila, id fijo = 1; la crea V2)
-- ---------------------------------------------------------------------
CREATE TABLE configuracion (
    id                          SMALLINT      PRIMARY KEY DEFAULT 1,
    nombre_empresa              VARCHAR(120)  NOT NULL,
    zona_horaria                VARCHAR(40)   NOT NULL DEFAULT 'America/Mexico_City',
    plazo_credito_default_dias  INT           NOT NULL,
    limite_credito_default      NUMERIC(12,2) NOT NULL DEFAULT 0,
    whatsapp_habilitado         BOOLEAN       NOT NULL DEFAULT FALSE,
    hora_envio_recordatorios    TIME          NOT NULL DEFAULT '09:00',
    proveedor_ia                VARCHAR(20)   NOT NULL DEFAULT 'NINGUNO',
    modelo_ia                   VARCHAR(80),

    CONSTRAINT ck_configuracion_unica    CHECK (id = 1),
    CONSTRAINT ck_configuracion_plazo    CHECK (plazo_credito_default_dias > 0),
    CONSTRAINT ck_configuracion_limite   CHECK (limite_credito_default >= 0),
    CONSTRAINT ck_configuracion_ia       CHECK (proveedor_ia IN ('NINGUNO', 'ANTHROPIC', 'OPENAI', 'GEMINI'))
);

-- ---------------------------------------------------------------------
-- 2. usuarios (oficina, repartidores/cobradores y admin)
-- La autenticacion (password, tokens) se agrega en una migracion posterior.
-- ---------------------------------------------------------------------
CREATE TABLE usuarios (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(120)  NOT NULL,
    telefono   VARCHAR(20),
    rol        VARCHAR(12)   NOT NULL,
    activo     BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('ADMIN', 'OFICINA', 'REPARTIDOR'))
);

-- ---------------------------------------------------------------------
-- 3. rutas de reparto
-- ---------------------------------------------------------------------
CREATE TABLE rutas (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_origen  VARCHAR(30)   NOT NULL,
    nombre         VARCHAR(100)  NOT NULL,
    repartidor_id  BIGINT,
    activo         BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_rutas_codigo_origen UNIQUE (codigo_origen),
    CONSTRAINT fk_rutas_repartidor    FOREIGN KEY (repartidor_id) REFERENCES usuarios (id)
);

-- ---------------------------------------------------------------------
-- 4. clientes (tienditas y abarrotes)
-- plazo_dias / limite NULL o 0 => se usa el default de configuracion
-- (la regla vive en el servicio, no en la tabla).
-- acepta_whatsapp: WhatsApp Business exige consentimiento (opt-in).
-- ---------------------------------------------------------------------
CREATE TABLE clientes (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_origen      VARCHAR(30)   NOT NULL,
    nombre_negocio     VARCHAR(150)  NOT NULL,
    contacto           VARCHAR(120),
    telefono_whatsapp  VARCHAR(16),
    direccion          VARCHAR(255),
    ruta_id            BIGINT,
    limite_credito     NUMERIC(12,2) NOT NULL DEFAULT 0,
    plazo_dias         INT     ,
    estado_credito     VARCHAR(12)   NOT NULL DEFAULT 'ACTIVO',
    acepta_whatsapp    BOOLEAN       NOT NULL DEFAULT FALSE,
    activo             BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en          TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_clientes_codigo_origen  UNIQUE (codigo_origen),
    CONSTRAINT fk_clientes_ruta           FOREIGN KEY (ruta_id) REFERENCES rutas (id),
    CONSTRAINT ck_clientes_limite         CHECK (limite_credito >= 0),
    CONSTRAINT ck_clientes_plazo          CHECK (plazo_dias IS NULL OR plazo_dias > 0),
    CONSTRAINT ck_clientes_estado_credito CHECK (estado_credito IN ('ACTIVO', 'REDUCIDO', 'SUSPENDIDO')),
    -- Formato E.164: +52 seguido de 10 digitos para Mexico (+528711234567)
    CONSTRAINT ck_clientes_telefono       CHECK (telefono_whatsapp IS NULL OR telefono_whatsapp ~ '^\+[1-9][0-9]{7,14}$')
);

CREATE INDEX ix_clientes_ruta ON clientes (ruta_id);

-- ---------------------------------------------------------------------
-- 5. importaciones (bitacora de cada Excel/CSV que se sube)
-- ---------------------------------------------------------------------
CREATE TABLE importaciones (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archivo_nombre   VARCHAR(255)  NOT NULL,
    importado_en     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario_id       BIGINT,
    filas_total      INT           NOT NULL DEFAULT 0,
    creadas          INT           NOT NULL DEFAULT 0,
    actualizadas     INT           NOT NULL DEFAULT 0,
    errores          INT           NOT NULL DEFAULT 0,
    detalle_errores  JSONB,        -- [{ "fila": 12, "folio": "A-123", "error": "..." }]

    CONSTRAINT fk_importaciones_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT ck_importaciones_conteos CHECK (filas_total >= 0 AND creadas >= 0
                                               AND actualizadas >= 0 AND errores >= 0)
);

-- ---------------------------------------------------------------------
-- 6. notas (cuentas por cobrar: una nota de venta a credito)
-- NO existe el estado VENCIDA: se calcula con
--   saldo > 0 AND fecha_vencimiento < hoy
-- ruta_id es una "foto" de la ruta al momento de la venta: si el cliente
-- cambia de ruta, sus notas viejas siguen contando para la ruta original.
-- ---------------------------------------------------------------------
CREATE TABLE notas (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_origen       VARCHAR(40)   NOT NULL,
    cliente_id         BIGINT        NOT NULL,
    ruta_id            BIGINT,
    importacion_id     BIGINT,
    fecha_emision      DATE          NOT NULL,
    fecha_vencimiento  DATE          NOT NULL,
    monto              NUMERIC(12,2) NOT NULL,
    saldo              NUMERIC(12,2) NOT NULL,
    estado             VARCHAR(10)   NOT NULL DEFAULT 'ABIERTA',
    creado_en          TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_notas_folio_origen  UNIQUE (folio_origen),
    CONSTRAINT fk_notas_cliente       FOREIGN KEY (cliente_id)     REFERENCES clientes (id),
    CONSTRAINT fk_notas_ruta          FOREIGN KEY (ruta_id)        REFERENCES rutas (id),
    CONSTRAINT fk_notas_importacion   FOREIGN KEY (importacion_id) REFERENCES importaciones (id),
    CONSTRAINT ck_notas_monto         CHECK (monto > 0),
    CONSTRAINT ck_notas_saldo         CHECK (saldo >= 0 AND saldo <= monto),
    CONSTRAINT ck_notas_fechas        CHECK (fecha_vencimiento >= fecha_emision),
    CONSTRAINT ck_notas_estado        CHECK (estado IN ('ABIERTA', 'PARCIAL', 'PAGADA', 'CANCELADA')),
    -- El estado tiene que cuadrar con el saldo (CANCELADA puede tener cualquier saldo)
    CONSTRAINT ck_notas_estado_saldo  CHECK (
        estado = 'CANCELADA'
        OR (estado = 'PAGADA'  AND saldo = 0)
        OR (estado = 'ABIERTA' AND saldo = monto)
        OR (estado = 'PARCIAL' AND saldo > 0 AND saldo < monto)
    )
);

CREATE INDEX ix_notas_cliente_estado ON notas (cliente_id, estado);
CREATE INDEX ix_notas_ruta           ON notas (ruta_id);
-- Cartera viva: dashboard, antiguedad, recordatorios y lista de cobro
CREATE INDEX ix_notas_vencimiento_pendientes ON notas (fecha_vencimiento) WHERE saldo > 0 AND estado <> 'CANCELADA';

-- ---------------------------------------------------------------------
-- 7. pagos (lo que entrega el cliente: un deposito, efectivo en ruta...)
-- uuid_dispositivo: lo genera el celular del repartidor; si reintenta
-- por falta de senal, el UNIQUE evita registrar el pago dos veces.
-- ---------------------------------------------------------------------
CREATE TABLE pagos (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id        BIGINT        NOT NULL,
    monto             NUMERIC(12,2) NOT NULL,
    fecha_pago        TIMESTAMPTZ   NOT NULL,
    metodo            VARCHAR(15)   NOT NULL,
    origen            VARCHAR(10)   NOT NULL,
    registrado_por    BIGINT,
    referencia        VARCHAR(100),
    comentario        VARCHAR(255),
    uuid_dispositivo  UUID,
    creado_en         TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_pagos_uuid_dispositivo UNIQUE (uuid_dispositivo),
    CONSTRAINT fk_pagos_cliente          FOREIGN KEY (cliente_id)     REFERENCES clientes (id),
    CONSTRAINT fk_pagos_registrado_por   FOREIGN KEY (registrado_por) REFERENCES usuarios (id),
    CONSTRAINT ck_pagos_monto            CHECK (monto > 0),
    CONSTRAINT ck_pagos_metodo           CHECK (metodo IN ('EFECTIVO', 'TRANSFERENCIA', 'DEPOSITO')),
    CONSTRAINT ck_pagos_origen           CHECK (origen IN ('OFICINA', 'RUTA'))
);

CREATE INDEX ix_pagos_cliente_fecha ON pagos (cliente_id, fecha_pago);
CREATE INDEX ix_pagos_fecha         ON pagos (fecha_pago);

-- ---------------------------------------------------------------------
-- 8. aplicaciones_pago (cuanto de cada pago se abona a cada nota)
-- Un pago de $500 puede liquidar dos notas viejas y abonar a una tercera.
-- La suma de aplicaciones <= pagos.monto la valida el servicio
-- (un CHECK no puede ver otras filas).
-- ---------------------------------------------------------------------
CREATE TABLE aplicaciones_pago (
    id       BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pago_id  BIGINT        NOT NULL,
    nota_id  BIGINT        NOT NULL,
    monto    NUMERIC(12,2) NOT NULL,

    CONSTRAINT uk_aplicaciones_pago_nota UNIQUE (pago_id, nota_id),
    CONSTRAINT fk_aplicaciones_pago      FOREIGN KEY (pago_id) REFERENCES pagos (id) ON DELETE CASCADE,
    CONSTRAINT fk_aplicaciones_nota      FOREIGN KEY (nota_id) REFERENCES notas (id),
    CONSTRAINT ck_aplicaciones_monto     CHECK (monto > 0)
);

CREATE INDEX ix_aplicaciones_nota ON aplicaciones_pago (nota_id);

-- ---------------------------------------------------------------------
-- 9. politica_recordatorios (cuando avisar, relativo al vencimiento)
-- dias_offset: -3 = tres dias antes, 0 = el dia que vence, 7 = una semana tarde.
-- No se borran filas (los recordatorios enviados las referencian): se desactivan.
-- ---------------------------------------------------------------------
CREATE TABLE politica_recordatorios (
    id                         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dias_offset                INT           NOT NULL,
    plantilla                  TEXT          NOT NULL,  -- texto con {cliente}, {folio}, {saldo}, {vencimiento}
    nombre_plantilla_whatsapp  VARCHAR(100),            -- plantilla aprobada en WhatsApp Business / Twilio ContentSid
    activo                     BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT uk_politica_dias_offset UNIQUE (dias_offset),
    CONSTRAINT ck_politica_dias_offset CHECK (dias_offset BETWEEN -30 AND 90)
);

-- ---------------------------------------------------------------------
-- 10. recordatorios (cada mensaje programado o enviado)
-- UNIQUE (nota_id, politica_id): si el scheduler corre dos veces el mismo
-- dia, al cliente no le llegan dos mensajes por la misma regla.
-- telefono_destino y mensaje son una foto de lo que se mando (auditoria).
-- ---------------------------------------------------------------------
CREATE TABLE recordatorios (
    id                    BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_id               BIGINT        NOT NULL,
    politica_id           BIGINT        NOT NULL,
    programado_para       DATE          NOT NULL,
    estado                VARCHAR(10)   NOT NULL DEFAULT 'PENDIENTE',
    intentos              INT           NOT NULL DEFAULT 0,
    telefono_destino      VARCHAR(16),
    mensaje               TEXT,
    mensaje_proveedor_id  VARCHAR(64),  -- SID de Twilio / id de WhatsApp Business
    error                 VARCHAR(500),
    enviado_en            TIMESTAMPTZ,
    creado_en             TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_recordatorios_nota_politica UNIQUE (nota_id, politica_id),
    CONSTRAINT fk_recordatorios_nota          FOREIGN KEY (nota_id)     REFERENCES notas (id),
    CONSTRAINT fk_recordatorios_politica      FOREIGN KEY (politica_id) REFERENCES politica_recordatorios (id),
    CONSTRAINT ck_recordatorios_estado        CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'FALLIDO', 'CANCELADO')),
    CONSTRAINT ck_recordatorios_intentos      CHECK (intentos >= 0),
    CONSTRAINT ck_recordatorios_enviado       CHECK (estado <> 'ENVIADO' OR enviado_en IS NOT NULL)
);

-- El scheduler busca: pendientes cuyo dia ya llego
CREATE INDEX ix_recordatorios_pendientes ON recordatorios (programado_para) WHERE estado = 'PENDIENTE';
CREATE INDEX ix_recordatorios_enviado_en ON recordatorios (enviado_en)      WHERE estado = 'ENVIADO';

-- ---------------------------------------------------------------------
-- 11. evaluaciones_riesgo (resultado de Ayax por cliente)
-- Una evaluacion por cliente + dia + modelo: recalcular el mismo dia
-- reemplaza (upsert); dias distintos forman el historial.
-- ---------------------------------------------------------------------
CREATE TABLE evaluaciones_riesgo (
    id                     BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id             BIGINT        NOT NULL,
    fecha_calculo          DATE          NOT NULL,
    modelo                 VARCHAR(5)    NOT NULL,
    score                  INT           NOT NULL,           -- 0 = sin riesgo ... 100 = no va a pagar
    nivel                  VARCHAR(5)    NOT NULL,
    dias_promedio_retraso  NUMERIC(6,2),                     -- dias de atraso promedio al pagar
    tendencia_deuda        NUMERIC(7,4),                     -- cambio relativo del saldo: 0.25 = +25 %
    uso_credito            NUMERIC(7,4),                     -- saldo / limite: 1.10 = 110 % (se paso)
    frecuencia_compra_dias NUMERIC(6,2),                     -- dias promedio entre notas
    saldo_vencido          NUMERIC(12,2) NOT NULL DEFAULT 0, -- foto al momento del calculo
    accion_recomendada     VARCHAR(30)   NOT NULL,
    explicacion            TEXT,
    generada_en            TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_evaluaciones_cliente_fecha_modelo UNIQUE (cliente_id, fecha_calculo, modelo),
    CONSTRAINT fk_evaluaciones_cliente  FOREIGN KEY (cliente_id) REFERENCES clientes (id),
    CONSTRAINT ck_evaluaciones_modelo   CHECK (modelo IN ('BASE', 'IA')),
    CONSTRAINT ck_evaluaciones_score    CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_evaluaciones_nivel    CHECK (nivel IN ('BAJO', 'MEDIO', 'ALTO')),
    CONSTRAINT ck_evaluaciones_accion   CHECK (accion_recomendada IN (
        'SIN_ACCION', 'COBRAR_PROXIMA_VISITA', 'OFRECER_DESCUENTO_PRONTO_PAGO',
        'REDUCIR_CREDITO', 'SUSPENDER_CREDITO'))
);

CREATE INDEX ix_evaluaciones_fecha_nivel ON evaluaciones_riesgo (fecha_calculo, nivel);
